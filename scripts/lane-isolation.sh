#!/usr/bin/env bash
# Per-lane isolation for a linked worktree at <primary>/.worktrees/<dir>.
# Usage: scripts/lane-isolation.sh setup|teardown   (run from inside the lane)
# The lane name derives from the worktree directory only, so one directory
# always maps to one set of resources (worktree-README.md § Lane isolation).
set -euo pipefail

action=${1:-}
fail() { echo "lane-isolation: $*" >&2; exit 1; }
[[ $action == setup || $action == teardown ]] || fail "usage: $0 setup|teardown"

checkout=$(git rev-parse --show-toplevel)
primary=$(dirname "$(git rev-parse --path-format=absolute --git-common-dir)")
cd "$checkout"

if [[ $checkout == "$primary" ]]; then
	[[ $action == setup ]] || fail "refusing teardown in the main checkout"
	echo "lane-isolation: main checkout uses the main stack; nothing to isolate"
	exit 0
fi
[[ $checkout == "$primary/.worktrees/"* ]] || fail "a lane must live under $primary/.worktrees/"

slug=$(basename "$checkout" | tr '[:upper:]' '[:lower:]' | tr -cd 'a-z0-9')
[[ $slug == lane* ]] || slug="lane$slug"
# The integration guard (scripts/lib/integration-env.sh) accepts only this shape.
[[ $slug =~ ^lane[a-z0-9]{1,20}$ ]] || fail "lane name '$slug' must match ^lane[a-z0-9]{1,20}$; rename the worktree directory"

lane=$slug
project="profitofexile-$lane"
host="$project.dev.localhost"
dev_db="profitofexile_${lane}"
test_db="profitofexile_${lane}_integration"
marker="lane-isolation:$checkout"
generated="# generated by make lane-setup"
services=(app frontend collector desktop)

# A lane compose file carrying 64-hex allocation tokens came from guarded v1
# provisioning (make worktree-create); its removal belongs to herdr-worktree.
if [[ -f docker-compose.lane.yml ]] && grep -Eq 'io\.pipeforge\.allocation: [a-f0-9]{64}' docker-compose.lane.yml; then
	[[ $action == setup ]] || fail "$lane was provisioned by make worktree-create; remove it with pipeforge herdr-worktree --action remove"
	echo "lane-isolation: $lane was provisioned by make worktree-create; left unchanged"
	exit 0
fi

psql_q() { docker exec -i postgres psql -X -U postgres -d postgres -v ON_ERROR_STOP=1 -At -c "$1"; }
# Prints "absent", "ours" or "foreign:<comment>" for a database.
db_owner() {
	local row
	row=$(psql_q "SELECT 'x' || coalesce(shobj_description(oid, 'pg_database'), '') FROM pg_database WHERE datname = '$1'") || return 1
	if [[ -z $row ]]; then echo absent
	elif [[ ${row#x} == "$marker" ]]; then echo ours
	else echo "foreign:${row#x}"; fi
}
compose() { docker compose --project-directory "$checkout" -p "$project" --profile collector -f docker-compose.lane.yml "$@"; }

if [[ $action == teardown ]]; then
	for file in .env .env.local; do
		[[ ! -f $file ]] || [[ $(head -1 "$file") == "$generated" ]] || fail "$file was not generated by lane-setup; not removing it"
	done
	# A lane with no lane compose file may still own containers by project label.
	if [[ -f docker-compose.lane.yml ]]; then compose down --remove-orphans
	elif [[ -n $(docker container ls -aq --filter "label=com.docker.compose.project=$project") ]]; then
		fail "containers of $project exist without docker-compose.lane.yml; inspect them"
	fi
	for db in "$dev_db" "$test_db"; do
		owner=$(db_owner "$db") || fail "cannot read $db from postgres"
		case $owner in
			absent) ;;
			ours) psql_q "DROP DATABASE \"$db\"" >/dev/null ;;
			# The full integration runner recreates its DB without the comment.
			"foreign:") [[ $db == "$test_db" ]] || fail "$db has no lane-isolation marker; not dropping it"
				psql_q "DROP DATABASE \"$db\"" >/dev/null ;;
			*) fail "$db belongs to ${owner#foreign:}; not dropping it" ;;
		esac
	done
	rm -rf .env .env.local docker-compose.lane.yml .worktree
	echo "lane-isolation: removed $project, $dev_db and $test_db"
	exit 0
fi

password=${WORKTREE_DB_PASSWORD:-profitofexile}
[[ $password =~ ^[A-Za-z0-9._~-]+$ ]] || fail "WORKTREE_DB_PASSWORD must use URL-unreserved characters only"
for file in .env .env.local; do
	[[ ! -f $file ]] || [[ $(head -1 "$file") == "$generated" ]] || fail "$file exists and was not generated by lane-setup; move it aside"
done

declare -A image
for service in "${services[@]}"; do
	image[$service]=$(docker image inspect --format '{{.Id}}' "profitofexile-$service:latest" 2>/dev/null) ||
		fail "image profitofexile-$service:latest missing; build the main stack first (make up in the main checkout)"
done

for db in "$dev_db" "$test_db"; do
	owner=$(db_owner "$db") || fail "cannot read $db from postgres"
	case $owner in
		absent) psql_q "CREATE DATABASE \"$db\" OWNER profitofexile" >/dev/null ;;
		ours) ;;
		"foreign:") [[ $db == "$test_db" ]] || fail "$db exists without this lane's marker; refusing to share it" ;;
		*) fail "$db belongs to ${owner#foreign:}; refusing to share it" ;;
	esac
	psql_q "COMMENT ON DATABASE \"$db\" IS '$marker'" >/dev/null
done

mkdir -p .worktree
chmod 700 .worktree
for cache in go-pkg frontend_node_modules desktop_cargo_registry desktop_cargo_git desktop_target desktop_node_modules; do mkdir -p ".worktree/$cache"; done
url="postgresql://profitofexile:$password@postgres:5432/$dev_db?sslmode=disable"
sed -e "s|__LANE__|$lane|g" -e "s|__DATABASE_URL__|\"$url\"|g" \
	-e "s|__APP_IMAGE__|${image[app]}|g" -e "s|__FRONTEND_IMAGE__|${image[frontend]}|g" \
	-e "s|__COLLECTOR_IMAGE__|${image[collector]}|g" -e "s|__DESKTOP_IMAGE__|${image[desktop]}|g" \
	-e "s|__[A-Z]*_TOKEN__|lane-isolation|g" docker-compose.worktree.yml >docker-compose.lane.yml
! grep -Eq '__[A-Z][A-Z_]*__' docker-compose.lane.yml || fail "unresolved field in docker-compose.lane.yml"
printf '%s' "$password" >.worktree/db-password
chmod 600 .worktree/db-password
printf '%s\nCOMPOSE_FILE=docker-compose.lane.yml\nCOMPOSE_PROJECT_NAME=%s\nINTEGRATION_DB=%s\n' "$generated" "$project" "$test_db" >.env
printf '%s\nexport INTEGRATION_DB := %s\nexport INTEGRATION_DB_PASSWORD := $(shell cat .worktree/db-password)\nexport COMPOSE_FILE := docker-compose.lane.yml\nexport COMPOSE_PROJECT_NAME := %s\n' \
	"$generated" "$test_db" "$project" >.env.local
printf "import config from '../frontend/vite.config';\nexport default { ...config, server: { ...config.server, allowedHosts: ['%s'], proxy: { '/api': { target: 'http://profitofexile_%s_app:8080', changeOrigin: true } } } };\n" \
	"$host" "$lane" >.worktree/vite.config.mts

compose run --rm -T app go run ./cmd/migrate up
echo "lane-isolation: $project ready: https://$host, databases $dev_db and $test_db"
