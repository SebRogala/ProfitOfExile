// Command harvest-tiers writes the Harvest family tiers the desktop fixture
// reads, classifying each family's Currency Exchange prices through
// internal/price/tier with no price cutoff (P49: the cheapest items are the
// feed) and depth unknown (C3: price only).
//
//	go run ./cmd/harvest-tiers -in cmd/harvest-tiers/testdata/prices-allflame-2026-09-08.json -out desktop/src/lib/harvest/__fixtures__/harvest-tiers.json
package main

import (
	"encoding/json"
	"flag"
	"log"
	"math"
	"os"

	"profitofexile/internal/price/tier"
)

const regenerateCommand = "go run ./cmd/harvest-tiers -in cmd/harvest-tiers/testdata/prices-allflame-2026-09-08.json -out desktop/src/lib/harvest/__fixtures__/harvest-tiers.json"

const note = "Generated by `" + regenerateCommand + "`; do not edit by hand. " +
	"Prices: the committed price file (Currency Exchange pooled VWAP, 25 clock hours 2026-09-08 00:00 → 2026-09-09 00:00 UTC, league Allflame). " +
	"Tiers: internal/price/tier, one group per family, no price cutoff (P49), depth unknown."

// policy has no cutoff: sub-5c oils and catalysts are tiered so they can be fed.
var policy = tier.Policy{DepthUnknown: true}

// familyTiers is one family's tiers in the desktop HarvestTiers shape
// (desktop/src/lib/harvest/seam.ts), less priceHour.
type familyTiers struct {
	BoundariesChaos  []float64         `json:"boundariesChaos"`
	ByItem           map[string]string `json:"byItem"`
	Names            []string          `json:"names"`
	TopBoundaryChaos *float64          `json:"topBoundaryChaos"`
}

type file struct {
	Note     string                 `json:"_note"`
	Families map[string]familyTiers `json:"families"`
}

// generate classifies each family of prices ({family: {itemId: chaos}}) as
// its own group.
func generate(prices map[string]map[string]float64) file {
	out := file{Note: note, Families: make(map[string]familyTiers, len(prices))}
	for fam, items := range prices {
		in := make([]tier.Item, 0, len(items))
		for id, chaos := range items {
			in = append(in, tier.Item{Group: fam, Key: id, Price: chaos})
		}
		res := tier.Classify(in, policy)

		byItem := make(map[string]string, len(res.Items))
		for k, c := range res.Items {
			byItem[k.Key] = c.Tier
		}
		b := res.Boundaries[fam]
		rounded := make([]float64, len(b.Boundaries))
		for i, x := range b.Boundaries {
			rounded[i] = math.Round(x*100) / 100
		}
		var top *float64
		if v, ok := res.TopBoundary[fam]; ok {
			top = &v
		}
		out.Families[fam] = familyTiers{
			BoundariesChaos:  rounded,
			ByItem:           byItem,
			Names:            b.Names,
			TopBoundaryChaos: top,
		}
	}
	return out
}

func encode(f file) []byte {
	enc, err := json.MarshalIndent(f, "", "  ")
	if err != nil {
		log.Fatalf("encode tiers: %v", err)
	}
	return append(enc, '\n')
}

func main() {
	in := flag.String("in", "", "price file: {family: {itemId: chaos}}")
	out := flag.String("out", "", "tier file to write")
	flag.Parse()
	if *in == "" || *out == "" {
		log.Fatal("usage: harvest-tiers -in <prices.json> -out <tiers.json>")
	}

	raw, err := os.ReadFile(*in)
	if err != nil {
		log.Fatalf("read prices: %v", err)
	}
	var prices map[string]map[string]float64
	if err := json.Unmarshal(raw, &prices); err != nil {
		log.Fatalf("decode prices: %v", err)
	}
	if err := os.WriteFile(*out, encode(generate(prices)), 0o644); err != nil {
		log.Fatalf("write tiers: %v", err)
	}
}
